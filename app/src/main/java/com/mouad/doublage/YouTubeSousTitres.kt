package com.mouad.doublage

import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.downloader.Downloader
import org.schabi.newpipe.extractor.downloader.Request
import org.schabi.newpipe.extractor.downloader.Response
import org.schabi.newpipe.extractor.exceptions.ReCaptchaException
import org.schabi.newpipe.extractor.localization.Localization
import org.schabi.newpipe.extractor.stream.StreamInfoItem
import java.net.HttpURLConnection
import java.net.URL

/**
 * Retrouve la vidéo YouTube en cours (titre + chaîne + durée lus dans le lecteur) et télécharge ses sous-titres.
 * À appeler hors du fil principal.
 */
object YouTubeSousTitres {

    private const val AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:128.0) Gecko/20100101 Firefox/128.0"

    private object Telechargeur : Downloader() {
        override fun execute(request: Request): Response {
            val c = URL(request.url()).openConnection() as HttpURLConnection
            c.connectTimeout = 15000; c.readTimeout = 20000
            c.requestMethod = request.httpMethod()
            c.setRequestProperty("User-Agent", AGENT)
            request.headers().forEach { (k, v) -> v.forEach { c.addRequestProperty(k, it) } }
            request.dataToSend()?.let { d -> c.doOutput = true; c.outputStream.use { it.write(d) } }
            val code = c.responseCode
            if (code == 429) { c.disconnect(); throw ReCaptchaException("YouTube demande une vérification", request.url()) }
            val corps = try {
                (if (code >= 400) c.errorStream else c.inputStream)?.bufferedReader()?.use { it.readText() } ?: ""
            } catch (_: Exception) { "" }
            val entetes = c.headerFields.filterKeys { it != null }
            val fin = c.url.toString()
            c.disconnect()
            return Response(code, c.responseMessage, entetes, corps, fin)
        }
    }

    @Volatile private var pret = false
    private fun initialiser() {
        if (pret) return
        synchronized(this) {
            if (!pret) { NewPipe.init(Telechargeur, Localization("fr", "CA")); pret = true }
        }
    }

    /** Résultat : les répliques à dire (déjà dans la langue de la traduction, ou à traduire). */
    class Resultat(
        val repliques: List<Pistes.Replique>,
        val langue: String,          // langue des répliques
        val description: String      // pour l'écran : « arabe (YouTube) », « turc auto → traduit »...
    )

    /** Adresse de la vidéo qui correspond au lecteur, ou null. */
    fun trouverVideo(titre: String, chaine: String, dureeMs: Long): String? {
        initialiser()
        val ex = ServiceList.YouTube.getSearchExtractor("$titre $chaine".trim())
        ex.fetchPage()
        return ex.initialPage.items.filterIsInstance<StreamInfoItem>()
            .map { it to Pistes.note(titre, chaine, dureeMs, it.name ?: "", it.uploaderName ?: "", it.duration) }
            .filter { it.second >= 0 }
            .maxByOrNull { it.second }?.first?.url
    }

    fun pistes(url: String): List<Pistes.Piste> {
        initialiser()
        val ex = ServiceList.YouTube.getStreamExtractor(url)
        ex.fetchPage()
        return ex.getSubtitles(MediaFormat.TRANSCRIPT1).map { Pistes.Piste(it.languageTag, it.isAutoGenerated, it.content) }
    }

    private fun telecharger(url: String): String {
        val c = URL(url).openConnection() as HttpURLConnection
        c.connectTimeout = 15000; c.readTimeout = 20000
        c.setRequestProperty("User-Agent", AGENT)
        try {
            if (c.responseCode != 200) return ""
            return c.inputStream.bufferedReader().use { it.readText() }
        } finally { c.disconnect() }
    }

    private fun lire(url: String): List<Pistes.Replique> =
        try { Pistes.regrouper(Pistes.lire(telecharger(url))) } catch (_: Exception) { emptyList() }

    /**
     * Ordre : 1) piste écrite dans la langue de la traduction, 2) traduction automatique de YouTube,
     * 3) piste originale (l'app la traduira elle-même). null = pas de sous-titres.
     */
    fun charger(url: String, source: String?, cible: String): Resultat? {
        val p = pistes(url)
        if (p.isEmpty()) return null
        Pistes.pisteCible(p, cible)?.let { pc ->
            val r = lire(pc.url)
            if (r.isNotEmpty()) return Resultat(r, cible, "${Langues.nom(cible)} (écrits par la chaîne)")
        }
        val orig = Pistes.pisteOriginale(p, source) ?: return null
        val lo = Pistes.court(orig.langue)
        if (lo == cible) {
            val r = lire(orig.url)
            return if (r.isEmpty()) null else Resultat(r, cible, "${Langues.nom(cible)}${if (orig.auto) " (auto)" else ""}")
        }
        val tr = lire(Pistes.urlTraduite(orig.url, cible))
        if (tr.isNotEmpty()) return Resultat(tr, cible,
            "${Langues.nom(lo)}${if (orig.auto) " auto" else ""} → ${Langues.nom(cible)} (traduits par YouTube)")
        val r = lire(orig.url)
        return if (r.isEmpty()) null else Resultat(r, lo,
            "${Langues.nom(lo)}${if (orig.auto) " auto" else ""} (traduits par l'app)")
    }
}
